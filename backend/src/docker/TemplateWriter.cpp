/// Writes text with LF line endings (important: server.properties and shell
/// scripts must not contain CRLF, otherwise the shell reports "not found").
bool writeLf(const QString &path, const QString &content, QString *error)
{
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        if (error)
            *error = QStringLiteral("cannot write %1").arg(path);
        return false;
    }
    QByteArray bytes = content.toUtf8();
    bytes.replace("\r\n", "\n");
    file.write(bytes);
    file.close();
    return true;
}

/// .cmd files are parsed more reliably with CRLF line endings.
bool writeCrlf(const QString &path, const QString &content, QString *error)
{
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        if (error)
            *error = QStringLiteral("cannot write %1").arg(path);
        return false;
    }
    QString text = content;
    text.replace(QLatin1String("\r\n"), QLatin1String("\n"));
    text.replace(QLatin1String("\n"), QLatin1String("\r\n"));
    file.write(text.toUtf8());
    file.close();
    return true;
}

